"""Results of one candidate setting next to the base -> a section of docs/pre_image_plan.md

Usage:
    .\\.venv\\Scripts\\python.exe scripts\\candidate_report.py --candidate stack_aug_samepair

Collects, for the base (stack_aug) and the candidate, per seed and as the mean over the
seeds: accuracy, macro-F1 and per-class recall on val-tiles and val at the kept epoch,
the epoch kept, and the RAM and GPU peaks of the training runs. Then applies the stop
rule (scripts/stop_rule.py) and writes everything, with the decision, into a generated
section at the end of the plan document.

Reads runs/<setting>_s<seed>/metrics.json only (val-tiles and val; src/train.py never
evaluates the test part). Trains nothing.
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from stop_rule import SEEDS, decide, setting_means  # noqa: E402
from src.dataset import CLASS_NAMES  # noqa: E402
from src.reporting import df_to_markdown, write_section  # noqa: E402

PARTS = ("val-tiles", "val")


def run_rows(runs_dir, setting, seeds=SEEDS):
    """One row per finished seed and part, plus one cost row per seed."""
    metrics, cost = [], []
    for seed in seeds:
        path = Path(runs_dir) / f"{setting}_s{seed}" / "metrics.json"
        if not path.exists():
            continue
        m = json.loads(path.read_text(encoding="utf-8"))
        for part in PARTS:
            b = m["best"][part]
            row = {"setting": setting, "seed": str(seed), "part": part,
                   "accuracy": b["accuracy"], "macro-F1": b["macro_f1"]}
            # recall of class c = of the buildings truly c, the share predicted c
            row.update({f"recall {name}": r for name, r in zip(CLASS_NAMES, b["recall"])})
            metrics.append(row)
        cost.append({"run": m["run_name"], "epoch kept": f"{m['best_epoch']} of {m['epochs_run']}",
                     "batch": m["batch_size"], "loader workers": m["num_workers"],
                     "train s/epoch": m["train_seconds_per_epoch"],
                     "RAM of this run, peak GB": m["run_peak_private_gb"],
                     "RAM free, minimum GB": m["ram_min_available_gb"],
                     "GPU peak GB (allocated)": m["gpu_peak_allocated_gb"],
                     "GPU peak GB (reserved)": m["gpu_peak_reserved_gb"]})
    return metrics, cost


def with_means(rows):
    """Append a "mean" row per setting and part to the per-seed rows."""
    df = pd.DataFrame(rows)
    numeric = [c for c in df.columns if c not in ("setting", "seed", "part")]
    means = df.groupby(["setting", "part"], sort=False)[numeric].mean().reset_index()
    means.insert(1, "seed", "mean")
    out = pd.concat([df, means], ignore_index=True)
    # keep each setting's block together: seeds first, then the mean, part by part
    order = {s: i for i, s in enumerate(df["setting"].unique())}
    out["_s"] = out["setting"].map(order)
    out["_p"] = out["part"].map({p: i for i, p in enumerate(PARTS)})
    out["_m"] = (out["seed"] == "mean").astype(int)
    return out.sort_values(["_p", "_s", "_m", "seed"]).drop(columns=["_s", "_p", "_m"])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--candidate", required=True)
    ap.add_argument("--baseline", default="stack_aug")
    ap.add_argument("--runs-dir", type=Path, default=Path("runs"))
    ap.add_argument("--doc", type=Path, default=Path("docs/pre_image_plan.md"))
    args = ap.parse_args(argv)

    metrics, cost = [], []
    for setting in (args.baseline, args.candidate):
        m, c = run_rows(args.runs_dir, setting)
        metrics += m
        cost += c
    table = with_means(metrics)
    baseline = setting_means(args.runs_dir, args.baseline)
    candidate = setting_means(args.runs_dir, args.candidate)
    decision, checks = decide(baseline, candidate)

    lines = [f"## Result: `{args.candidate}`",
             f"Generated by `scripts/candidate_report.py`. Baseline `{args.baseline}`; both "
             "with seeds 0, 1, 2, each run at the epoch kept by the 3-epoch selection rule. "
             "Validation only.",
             "### Stop rule",
             "\n".join(f"- {'PASS' if ok else 'FAIL'}: {text}" for text, ok in checks),
             f"**Decision: {decision}.**",
             "### Metrics per seed and mean",
             df_to_markdown(table, "{:.3f}", index=False),
             "### Training cost",
             df_to_markdown(pd.DataFrame(cost), "{:.2f}", index=False)]
    write_section(args.doc, f"result-{args.candidate}", "\n\n".join(lines))
    print(table.round(3).to_string(index=False))
    print(pd.DataFrame(cost).round(2).to_string(index=False))
    for text, ok in checks:
        print(f"  [{'pass' if ok else 'FAIL'}] {text}")
    print(f"decision: {decision}")
    return decision


if __name__ == "__main__":
    main()
